fun AppColorScheme.scheme(dark: Boolean): ColorScheme = when (this) {
    AppColorScheme.Dynamic, AppColorScheme.Honey -> if (dark) HoneyDark else HoneyLight
    AppColorScheme.Indigo -> if (dark) IndigoDark else IndigoLight
    AppColorScheme.Forest -> if (dark) ForestDark else ForestLight
    AppColorScheme.Rose -> if (dark) RoseDark else RoseLight
}
